import React, { useRef } from "react";
import { FileDown, Printer } from "lucide-react";
import type { SimulationResult } from "@/domain/reference/types";
import { platform } from "@/presentation/theme/platformStyles";
import { useReferenceData } from "@/presentation/providers/ReferenceDataProvider";
import { DECLARATION_PRINT_CSS } from "@/presentation/features/export/declarationPrintStyles";

interface DeclarationSummaryProps {
  simulation: SimulationResult;
  darkMode?: boolean;
}

function formatAmount(value: number, currency?: string): string {
  const formatted = value.toLocaleString("en-US", { maximumFractionDigits: 2 });
  return currency ? `${formatted} ${currency}` : formatted;
}

export const DeclarationSummary: React.FC<DeclarationSummaryProps> = ({
  simulation,
  darkMode = true,
}) => {
  const printRef = useRef<HTMLDivElement>(null);
  const { countries } = useReferenceData();

  const originCountry = countries.find((c) => c.code === simulation.origin);
  const destCountry = countries.find((c) => c.code === simulation.destination);
  const originThreshold = simulation.originValueThresholdPct ?? 40;
  const vatPct = destCountry ? destCountry.vatRate * 100 : 0;

  const handlePrint = () => {
    const printContent = printRef.current?.innerHTML;
    if (!printContent) return;

    const win = window.open("", "_blank");
    if (!win) return;

    win.document.write(`<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>AfCFTA certificate — ${simulation.id}</title>
  <style>${DECLARATION_PRINT_CSS}</style>
</head>
<body onload="window.print();window.close()">
  <div class="cert-sheet">${printContent}</div>
</body>
</html>`);
    win.document.close();
  };

  const downloadTextReceipt = () => {
    const textContent = `
========================================================================
             AfCFTA preferential declaration sheet
========================================================================
ID Simulation       : ${simulation.id}
Issue date          : ${new Date(simulation.date).toLocaleDateString("en-US")}
Concession year    : ${simulation.year}
------------------------------------------------------------------------
Sender / Origin section:
Origin country      : ${originCountry?.name} (${simulation.origin})
Local currency      : ${originCountry?.currency}
Declared value      : ${formatAmount(simulation.declaredValueLocal, originCountry?.currency)} (${formatAmount(simulation.declaredValueUSD, "USD")})
Local added value   : ${simulation.localOriginValueRatio}% (Required: >= ${originThreshold}%)
AfCFTA eligible     : ${simulation.isEligiblePrefAfCFTA ? "YES" : "NO"}

Recipient / Customs section:
Destination country : ${destCountry?.name} (${simulation.destination})
Product description : ${simulation.productDescription}
HS code nomenclature: ${simulation.hsCode}

RATES & CALCULATIONS:
Customs duty        : ${(simulation.appliedTariffRate * 100).toFixed(1)}% → ${formatAmount(simulation.dutyPaidLocal, destCountry?.currency)}
Destination VAT (${vatPct.toFixed(2)}%): ${formatAmount(simulation.vatPaidLocal, destCountry?.currency)}
------------------------------------------------------------------------
Estimated total     : ${formatAmount(simulation.totalTaxLocal, destCountry?.currency)} (≈ ${formatAmount(simulation.totalTaxUSD, "USD")})
========================================================================
Document generated by RegTech — AfCFTA customs assistant
========================================================================
    `;
    const blob = new Blob([textContent], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `Declaration_AfCFTA_${simulation.id}.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const thClass = `px-4 py-3 text-left text-[10px] uppercase tracking-wider font-semibold ${
    darkMode ? "bg-dark-secondary text-gray-400" : "bg-gray-100 text-gray-600"
  }`;
  const tdClass = `px-4 py-3 text-sm ${darkMode ? "text-gray-200" : "text-gray-800"}`;
  const tdNum = `${tdClass} text-right font-mono tabular-nums whitespace-nowrap`;

  return (
    <div className="space-y-8 font-sans" id="summary_receipt_panel">
      <div className="flex flex-wrap items-center justify-between gap-4">
        <p className={`text-sm ${platform.textMuted(darkMode)}`}>
          Ref. {simulation.id} · {new Date(simulation.date).toLocaleDateString("en-US")}
        </p>
        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={downloadTextReceipt}
            id="btn_download_receipt"
            className={`flex items-center gap-1.5 rounded-full border px-3 py-2 text-xs font-medium ${
              darkMode
                ? "bg-dark-secondary text-gray-300 hover:bg-gray-700 border-gray-700"
                : "bg-white text-gray-700 hover:bg-gray-50 border-gray-300"
            }`}
          >
            <FileDown className="w-3.5 h-3.5" />
            Export TXT
          </button>
          <button
            type="button"
            onClick={handlePrint}
            id="btn_print_receipt"
            className={`flex items-center gap-1.5 rounded-full px-3 py-2 text-xs font-medium ${platform.buttonPrimary}`}
          >
            <Printer className="w-3.5 h-3.5" />
            Print
          </button>
        </div>
      </div>

      <div id="printable_summary_content" ref={printRef} className="space-y-8">
        <div className={`border-b border-dashed pb-6 text-center ${platform.borderSubtle(darkMode)}`}>
          <p className="text-xs font-semibold uppercase tracking-widest text-primary-500">
            AfCFTA preferential customs regime
          </p>
          <h2 className={`mt-2 text-xl font-bold font-display ${platform.textPrimary(darkMode)}`}>
            Pro-forma eligibility certificate
          </h2>
        </div>

        {simulation.isEligiblePrefAfCFTA ? (
          <p className={`text-sm leading-relaxed ${platform.textSecondary(darkMode)}`}>
            <span className="font-semibold text-primary-500">Preferential treatment confirmed.</span>{" "}
            Local value addition {simulation.localOriginValueRatio}% (threshold {originThreshold}%). Tariff concession for {simulation.year}.
          </p>
        ) : (
          <p className="text-sm leading-relaxed text-rose-500">
            <span className="font-semibold">Standard customs regime applied.</span>{" "}
            {simulation.sensitiveExclusion
              ? "Sensitive product or excluded from the AfCFTA agreement."
              : `Insufficient local value addition (${simulation.localOriginValueRatio}% / threshold ${originThreshold}%).`}{" "}
            Duties collected at the full rate.
          </p>
        )}

        <div className={`cert-grid grid grid-cols-1 gap-8 pb-8 mb-8 border-b ${
          darkMode ? "border-gray-800" : "border-gray-200"
        }`}>
          <div>
            <h3 className={`text-xs font-semibold uppercase tracking-wide ${platform.textMuted(darkMode)}`}>
              Origin &amp; sender
            </h3>
            <p className={`name font-bold text-sm ${darkMode ? "text-white" : "text-gray-900"}`}>
              {originCountry?.name ?? simulation.origin}
            </p>
            <p className={`sub text-xs mt-1 ${darkMode ? "text-gray-400" : "text-gray-600"}`}>
              AfCFTA exporter · Code {simulation.origin}
            </p>
            <p className={`mt-3 text-sm ${platform.textSecondary(darkMode)}`}>
              Declared value:{" "}
              <span className={platform.textPrimary(darkMode)}>
                {formatAmount(simulation.declaredValueLocal, originCountry?.currency)}
              </span>
              <span className={platform.textMuted(darkMode)}> · ≈ {formatAmount(simulation.declaredValueUSD, "USD")}</span>
            </p>
          </div>

          <div>
            <h3 className={`text-xs font-semibold uppercase tracking-wide ${platform.textMuted(darkMode)}`}>
              Destination &amp; customs
            </h3>
            <p className={`mt-1 text-sm font-semibold ${platform.textPrimary(darkMode)}`}>
              {destCountry?.name ?? simulation.destination}
            </p>
            <p className={`mt-1 text-xs ${platform.textMuted(darkMode)}`}>
              Customs territory · Code {simulation.destination}
            </p>
            <p className={`mt-3 text-sm ${platform.textSecondary(darkMode)}`}>
              HS {simulation.hsCode} — {simulation.productDescription}
            </p>
          </div>
        </div>

        <div className={`space-y-2 border-b pb-6 text-sm ${platform.borderSubtle(darkMode)}`}>
          <p className={`font-semibold ${platform.textPrimary(darkMode)}`}>Origin rule report (AFT)</p>
          <div className={`row flex justify-between py-2 border-b text-sm font-mono ${
            darkMode ? "border-gray-800" : "border-gray-200"
          }`}>
            <span>Local added value</span>
            <span className="font-bold">{simulation.localOriginValueRatio}%</span>
          </div>
          <div className="row flex justify-between py-2 text-sm font-mono">
            <span>AfCFTA compliance threshold</span>
            <span className={darkMode ? "text-gray-400" : "text-gray-600"}>≥ {originThreshold}%</span>
          </div>
        </div>

        <p className={`cert-section-title mb-3 ${darkMode ? "text-gray-500" : "text-gray-500"}`}>
          Taxation structure
        </p>
        <div className={`rounded-2xl overflow-hidden border mb-8 ${
          darkMode ? "border-gray-800" : "border-gray-200"
        }`}>
          <table className="cert-table w-full border-collapse text-sm">
            <thead>
              <tr>
                <th className={thClass}>Tax nature</th>
                <th className={`${thClass} text-right`}>Applied rate</th>
                <th className={`${thClass} text-right`}>Amount ({destCountry?.currency ?? "—"})</th>
              </tr>
            </thead>
            <tbody>
              <tr className={darkMode ? "border-gray-800" : "border-gray-100"}>
                <td className={tdClass}>Customs duties</td>
                <td className={tdNum}>
                  {simulation.isEligiblePrefAfCFTA ? (
                    <>
                      {(simulation.appliedTariffRate * 100).toFixed(1)}%
                      <span className={`text-[10px] line-through ml-2 ${darkMode ? "text-gray-500" : "text-gray-400"}`}>
                        {(simulation.baseTariffRate * 100).toFixed(1)}%
                      </span>
                    </>
                  ) : (
                    `${(simulation.baseTariffRate * 100).toFixed(1)}%`
                  )}
                </td>
                <td className={tdNum}>{formatAmount(simulation.dutyPaidLocal, destCountry?.currency)}</td>
              </tr>
              <tr>
                <td className={tdClass}>Local VAT</td>
                <td className={tdNum}>{vatPct.toFixed(2)}%</td>
                <td className={tdNum}>{formatAmount(simulation.vatPaidLocal, destCountry?.currency)}</td>
              </tr>
              <tr className={`total ${darkMode ? "bg-dark-primary/80" : "bg-gray-50"}`}>
                <td className={`${tdClass} font-bold`} colSpan={2}>
                  Total taxes
                  <span className={`total-usd block text-[11px] font-normal mt-1 ${platform.totalAmount(darkMode)}`}>
                    Equivalent ≈ {formatAmount(simulation.totalTaxUSD, "USD")}
                  </span>
                </td>
                <td className={`${tdNum} font-bold text-base ${platform.totalAmount(darkMode)} total-xaf`}>
                  {formatAmount(simulation.totalTaxLocal, destCountry?.currency)}
                </td>
              </tr>
            </tbody>
          </table>
        </div>

        <div
          className={`cert-footer flex flex-wrap justify-between gap-4 pt-6 border-t border-dashed text-[10px] font-mono ${
            darkMode ? "border-gray-800 text-gray-500" : "border-gray-300 text-gray-500"
          }`}
        >
          <div>
            <div>Document generated by RegTech — AfCFTA customs assistant</div>
            <div className="mt-1">Generated on {new Date(simulation.date).toLocaleString("en-US")}</div>
          </div>
          <div className="text-right">
            <div className="font-bold">RegTech</div>
            <div>Pro-forma eligibility certificate</div>
          </div>
        </div>
      </div>
    </div>
  );
};
